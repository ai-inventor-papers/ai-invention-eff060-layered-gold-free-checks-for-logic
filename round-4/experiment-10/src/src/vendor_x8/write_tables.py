#!/usr/bin/env python3
"""results/tables.md: every headline table, generated from results/*.json|csv (no hand-typed numbers)."""
from __future__ import annotations

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "results"


def f(x, d=3):
    try:
        x = float(x)
    except (TypeError, ValueError):
        return "NA"
    return "NA" if x != x else f"{x:.{d}f}"


def ci(c, d=3):
    return "[NA]" if not c or c[0] is None else f"[{f(c[0], d)}, {f(c[1], d)}]"


def main():
    L = []
    A = json.loads((R / "analysis_hyb.json").read_text())
    sel = json.loads((R / "selection.json").read_text())
    L += ["# Tables (generated by src/write_tables.py)", "",
          "Orientation: every score is higher = more likely ERROR. E = dataset E real generator outputs (R_AB = tiers A+B, "
          "LLM rows, CONTESTED and reading_choice excluded); CIs = sentence-cluster bootstrap (B=2000). PERTURB = synthetic "
          "mutants/controls, base-cluster bootstrap; never pooled with E.", "",
          "## T1. Part A selection (pre-registered rule, results/selection.json)", "",
          "| variant | RENAME FA (i) exp D | (ii) PERTURB RENAME_SYN | (iii) PERTURB RENAME_NONCE | eligible | E strat. AUROC R_AB |",
          "|---|---|---|---|---|---|"]
    for v in ("HYB", "NF-anchored"):
        e = sel["evidence"][v]["rename_FA"]
        L.append(f"| {v} | {f(e['i_expD_RENAME'])} | {f(e['ii_PERTURB_RENAME_SYN'])} | {f(e['iii_PERTURB_RENAME_NONCE'])} | "
                 f"{sel['evidence'][v]['eligible']} | {f(sel['E_strat_auroc_R_AB'][v])} |")
    L += [f"| ALIGN (reference) | | | | not a candidate | {f(sel['E_strat_auroc_R_AB']['ALIGN'])} |", "",
          f"**Frozen variant: {sel['frozen_variant']}** -- {sel['note']}", "",
          "## T2. E: stratified AUROC (95% CI) per subset", "",
          "| subset | n (err) | c_hyb | c_align | c_nf | g_hyb | g_align | g_nf | p_peer_text |", "|---|---|---|---|---|---|---|---|---|"]
    for name, ev in A["E"].items():
        m = ev.get("metrics", {})
        cells = [f"{f(m[k]['strat_auroc'])} {ci(m[k]['strat_auroc_ci'])}" if k in m else "NA"
                 for k in ("c_hyb", "c_align", "c_nf", "g_hyb", "g_align", "g_nf", "p_peer_text")]
        L.append(f"| {name} | {ev['n']} ({ev['n_error']}) | " + " | ".join(cells) + " |")
    L += ["", "## T3. E: paired Delta stratified AUROC (95% CI, same rows)", "",
          "| subset | HYB-ALIGN | HYB-NF | NF-ALIGN | g_hyb-g_align | HYB-local judge (Qwen3-8B disg, bf16 exp 5) | ALIGN-local judge |",
          "|---|---|---|---|---|---|---|"]
    for name, ev in A["E"].items():
        p = ev.get("paired", {})
        j = ev.get("vs_judge_local_qwen8b_disg", {}).get("paired", {})

        def g(d, k):
            return f"{f(d[k]['delta_strat_auroc'])} {ci(d[k]['ci_strat'])}" if k in d else "NA"
        L.append(f"| {name} | {g(p, 'c_hyb - c_align')} | {g(p, 'c_hyb - c_nf')} | {g(p, 'c_nf - c_align')} | {g(p, 'g_hyb - g_align')} | "
                 f"{g(j, 'c_hyb - judge_local_qwen8b_disg')} | {g(j, 'c_align - judge_local_qwen8b_disg')} |")
    au = A["new_agreement_audit"]
    L += ["", "## T4. Over-alignment audit on real E pairs (unordered candidate-peer pairs)", "",
          "| pair group | n pairs | label-discordant / both labelled | discordance rate | candidate ERROR share |", "|---|---|---|---|---|"]
    for gname in ("ALIGN_agree", "NEW_hyb_not_align", "DISAGREE_hyb_false"):
        d = au["label_discordance"].get(gname, {})
        c = au["candidate_error_share"].get(gname, {})
        L.append(f"| {gname} | {au['n_unordered_pairs'].get(gname)} | {d.get('discordant')}/{d.get('both_labelled')} | {f(d.get('rate'))} | {f(c.get('rate'))} |")
    oa = A["over_alignment"]
    L += ["", "## T5. Over-alignment probes: recall at the frozen SCREEN threshold", "",
          "| probe | c_align | c_nf | c_hyb | g_hyb |", "|---|---|---|---|---|"]
    for k in oa["c_align"]:
        L.append(f"| {k} (n={oa['c_align'][k]['n']}) | " + " | ".join(f"{f(oa[m][k]['recall'])}" for m in ("c_align", "c_nf", "c_hyb", "g_hyb")) + " |")
    L += ["", "## T6. Complexity (E R_AB): AUROC by bin", "", "| dimension | bin | n (err) | c_hyb | c_align | c_nf | HYB-ALIGN [CI] |", "|---|---|---|---|---|---|---|"]
    for dim, bins in A["complexity"].items():
        for b, v in bins.items():
            L.append(f"| {dim} | {b} | {v['n']} ({v['n_error']}) | {f(v['c_hyb'])} | {f(v['c_align'])} | {f(v['c_nf'])} | "
                     f"{f(v['hyb_minus_align'])} {ci(v['hyb_minus_align_ci'])} |")
    # ---- invariance
    inv = list(csv.DictReader((R / "invariance_table.csv").open()))
    L += ["", "## T7. Invariance: false alarms (FA) on meaning-preserving rewrites of CORRECT bases, flip rate separately", "",
          "FA = tie-aware share of rewritten CORRECT items flagged; base_FA = share of their unrewritten bases flagged; flip = |flag(rewrite) - flag(base)| "
          "with a coupled tie draw. PERTURB rows: E bases, PRIMARY (E-derived) thresholds. exp D rows: screen pools.", "",
          "| metric | family | source | threshold | n | FA [CI] | base_FA | flip |", "|---|---|---|---|---|---|---|---|"]
    keep_m = {"c_align", "c_nf", "c_hyb", "g_hyb", "p_peer_text", "p_text", "l2_bow", "l3_z3", "sc5_local_eq_frac", "judge_cheap_disg",
              "judge_local_qwen8b_disg", "judge_local_llama8b_disg", "rt_nli_min_local", "rt_embed_cos_local", "S4_local"}
    for r in inv:
        if r["metric"] in keep_m and r["subset"] in ("E_bases", "all") and not (r["source"].startswith("PERTURB") and r["subset"] == "all"):
            L.append(f"| {r['metric']} | {r['family']} | {r['source']} | {r['threshold']} | {r['n_rows']} | {f(r['FA_on_correct'])} "
                     f"[{f(r['FA_ci_lo'])}, {f(r['FA_ci_hi'])}] | {f(r.get('base_FA'))} | {f(r.get('flip_rate'))} |")
    # ---- PERTURB sensitivity
    sens = list(csv.DictReader((R / "perturb_sensitivity.csv").open()))
    ops = ["NEG", "REV", "QUANT", "RESTR", "CONN", "DROP", "ADD", "ADD[ADD_FOREIGN]", "ADD[ADD_INTERNAL]", "SWAP", "BIND", "MEANING_RENAME"]
    mets = sorted({r["metric"] for r in sens}, key=lambda m: (not m.startswith(("c_", "g_")), m))
    for col, title in (("recall_primary", "T8. PERTURB recall at the PRIMARY threshold (E bases, polarities pooled)"),
                       ("within_base_auroc", "T9. PERTURB within-base AUROC (mutants vs same-base non-rename controls + BASE; E bases)")):
        L += ["", f"## {title}", "", "| metric | " + " | ".join(ops) + " |", "|---" * (len(ops) + 1) + "|"]
        for m in mets:
            cells = []
            for op in ops:
                r = next((r for r in sens if r["metric"] == m and r["operator"] == op and r["polarity"] == "ALL" and r["subset"] == "E_bases"), None)
                cells.append(f(r.get(col)) if r else "NA")
            L.append(f"| {m} | " + " | ".join(cells) + " |")
    du = list(csv.DictReader((R / "perturb_downup.csv").open()))
    L += ["", "## T10. DOWN vs UP matched pairs (all operators)", "", "| metric | n pairs | recall DOWN | recall UP | DOWN-UP [CI] | McNemar b/c (p) | symmetric? |",
          "|---|---|---|---|---|---|---|"]
    for r in du:
        if r["operator"] == "ALL":
            L.append(f"| {r['metric']} | {r['n_pairs']} | {f(r['recall_DOWN'])} | {f(r['recall_UP'])} | {f(r['diff_DOWN_minus_UP'])} "
                     f"[{f(r['ci_lo'])}, {f(r['ci_hi'])}] | {r['mcnemar_down_only']}/{r['mcnemar_up_only']} ({f(r['mcnemar_p'])}) | {r['polarity_symmetric_|diff|<0.05']} |")
    cov = list(csv.DictReader((R / "coverage_perturb.csv").open()))
    L += ["", "## T11. PERTURB coverage (5,402 rows)", "", "| metric | scored ok | fail-filled | not scorable | reasons |", "|---|---|---|---|---|"]
    for r in cov:
        L.append(f"| {r['metric']} | {r['n_scored_ok']} | {r['n_fail_filled']} | {r['n_not_scorable']} | {r['reasons']} |")
    if (R / "typing.csv").exists():
        ty = list(csv.DictReader((R / "typing.csv").open()))
        L += ["", "## T12. Part C: error-type identification accuracy (E-base mutants)", "",
              "| operator | n | majority | peer medoid (ALIGN) strict | lenient | repair found | HYB medoid strict | ORACLE strict | flash-lite judge | local judge |",
              "|---|---|---|---|---|---|---|---|---|---|"]
        for r in ty:
            L.append(f"| {r['operator']} | {r['n']} | {f(r['majority_baseline'])} | {f(r['medoid_align_strict_acc'])} | {f(r['medoid_align_lenient_acc'])} | "
                     f"{f(r['medoid_align_repair_found_rate'])} | {f(r['medoid_hyb_strict_acc'])} | {f(r['oracle_strict_acc'])} | {f(r.get('judge_cheap_acc'))} | {f(r.get('judge_local_acc'))} |")
    (R / "tables.md").write_text("\n".join(L) + "\n")
    print(f"tables.md: {len(L)} lines")


if __name__ == "__main__":
    main()
