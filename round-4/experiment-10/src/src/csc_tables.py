"""results/tables.md: every table generated from result files (a '# source:' line per table; no hand-typed numbers)
+ results/deviations.json."""
from __future__ import annotations

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "results"
DATA = ROOT / "data"
E8 = Path(__file__).resolve().parents[4] / "round-3/experiment-8/src"


def rcsv(p: Path) -> list[dict]:
    with p.open() as f:
        return list(csv.DictReader(f))


def md(rows: list[dict], cols: list[str]) -> str:
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in rows:
        out.append("| " + " | ".join("" if r.get(c) in (None, "") else str(r.get(c)) for c in cols) + " |")
    return "\n".join(out)


def ci(r, a, lo, hi):
    if r.get(a) in (None, ""):
        return ""
    return f"{r[a]} [{r.get(lo)}, {r.get(hi)}]"


def main() -> None:
    L = []
    pre = json.loads((RES / "prereg_csc_P.json").read_text())
    dv = pre["deviation_D_BUDGET"]
    ledger = [json.loads(x) for x in (RES / "api_cost_ledger.jsonl").read_text().splitlines() if x.strip()]
    L.append("# CSC on PERTURB and R_COMP: result tables (auto-generated by src/csc_tables.py)\n")
    L.append("Orientation everywhere: higher score = more likely ERROR; flag at c > 0.5 (pre-registered). "
             "e = share of MUTANTS endorsed (c <= 0.5); recall = 1 - e; FA = share of CORRECT rows flagged. CIs: "
             "base-clustered bootstrap (B = 2000, seed 0) for PERTURB, sentence-clustered for typing, "
             "template-stratified sentence bootstrap for SIG AUROC.\n")
    L.append("## T0. Status: the pre-registered CSC peers could not be generated\n")
    L.append("# source: results/prereg_csc_P.json (deviation_D_BUDGET), results/api_cost_ledger.jsonl\n")
    L.append(f"{dv['what']}\n\nAPI calls attempted by this artifact: {len(ledger)} ledger records, total "
             f"${sum(float(x.get('cost_usd') or 0) for x in ledger):.7f}. Statuses: "
             f"{sorted({x['status'] for x in ledger})}.\n\nConsequence: gates G3-P, G4 and MT(E) are UNTESTED. Zero-cost "
             "arms reported instead (labelled in every table): SIGPROXY (exp-7 SIG outputs of the same four families, "
             "R_COMP), LOCAL2 (secondary small local peers, same CSC prompt), FREE3 / exp-8 free consensus baselines, "
             "ORACLE_samevocab typing.\n")
    # T1 structural fact
    ss = rcsv(RES / "sig_sharing.csv")
    L.append("## T1. KEY STRUCTURAL FACT: which PERTURB rows keep their base's signature\n")
    L.append("# source: results/sig_sharing.csv (computed from the parsed formulas, not assumed)\n")
    allrows = [r for r in ss if r["base_source"] == "ALL"]
    shared = sorted({r["op_label"] for r in allrows if float(r["share_sharing_base_sig"]) == 1.0})
    partial = sorted({r["op_label"] for r in allrows if 0 < float(r["share_sharing_base_sig"]) < 1.0})
    new = sorted({r["op_label"] for r in allrows if float(r["share_sharing_base_sig"]) == 0.0})
    L.append(f"Signature-preserving (100% share the base signature, so CSC peers for them ARE the base's peers): {', '.join(shared)}. "
             f"Partly new: {', '.join(partial)}. Always new (need their own peers): {', '.join(new)}. "
             "Consequence: for every signature-preserving mutant, CSC peers cannot have seen the error through the cue; "
             "a peer that endorses the (CORRECT) base cannot also endorse the mutant (they are z3 non-equivalent), so "
             "recall on these operators is bounded below by base endorsement. Anchoring can only act through NEW "
             "symbols (ADD_FOREIGN, MEANING_RENAME, RENAME_*, most BIND/DROP).\n")
    L.append(md(ss, ["op_label", "base_source", "n_rows", "n_unique_sigs", "n_new_sigs_vs_base", "share_sharing_base_sig"]))
    # T2 anchoring
    an = rcsv(RES / "anchoring.csv")
    L.append("\n## T2. Mutant endorsement e (and recall) per operator, polarity pooled\n")
    L.append("# source: results/anchoring.csv\n")
    for src in ("E", "RCOMP"):
        sub = [r for r in an if r["polarity"] == "ALL" and r["base_source"] == src]
        vs = []
        for r in sub:
            if r["variant"] not in vs:
                vs.append(r["variant"])
        ops = []
        for r in sub:
            if r["op_label"] not in ops:
                ops.append(r["op_label"])
        rows = []
        for op in ops:
            rec = {"op_label": op}
            for v in vs:
                x = next((r for r in sub if r["op_label"] == op and r["variant"] == v), None)
                rec[v] = f"{x['e']} (n={x['n']})" if x else ""
            rows.append(rec)
        L.append(f"\n### base_source = {src}: e = share of mutants endorsed at c <= 0.5\n")
        L.append(md(rows, ["op_label"] + vs))
    L.append("\n## T3. Recall conditional on base endorsement (removes the base-endorsement artefact), all mutants\n")
    L.append("# source: results/anchoring.csv (op_label = ALL_MUTANTS, polarity = ALL)\n")
    L.append(md([r for r in an if r["op_label"] == "ALL_MUTANTS" and r["polarity"] == "ALL" and r["base_source"] != "ALL"],
                ["variant", "base_source", "n", "n_insufficient", "e", "e_lo", "e_hi", "e_excl_insufficient", "recall_eq1",
                 "n_base_endorsed", "recall_given_base_endorsed",
                 "n_base_not_endorsed", "recall_given_base_not_endorsed"]))
    L.append("\n## T3b. DOWN vs UP (polarity), all mutants\n")
    L.append("# source: results/anchoring.csv\n")
    L.append(md([r for r in an if r["op_label"] == "ALL_MUTANTS" and r["polarity"] != "ALL" and r["base_source"] != "ALL"],
                ["variant", "base_source", "polarity", "n", "e", "e_lo", "e_hi"]))
    # T4 d by length
    dl = rcsv(RES / "d_by_length.csv")
    L.append("\n## T4. d on the verified BASES (label-certain CORRECT) by length and number of conditions\n")
    L.append("# source: results/d_by_length.csv\n")
    cols = ["variant", "base_source", "n_bases", "d_all", "tercile_cuts_words", "d_T1", "d_T2", "d_T3", "logit_slope_per10words",
            "slope_lo", "slope_hi"]
    L.append(md(dl, cols))
    pc = rcsv(RES / "paired_cue_effect.csv")
    L.append("\n## T4b. Paired cue effect: cued vs uncued peers of the same families on the SAME rows\n")
    L.append("# source: results/paired_cue_effect.csv (flag = score > 0.5; base-clustered bootstrap; descriptive)\n")
    L.append(md([dict(r, diff=ci(r, "a_minus_b", "lo", "hi")) for r in pc],
                ["a", "b", "quantity", "n", "n_bases", "a_value", "b_value", "diff"]))
    # T5 controls
    cf = rcsv(RES / "controls_fa.csv")
    L.append("\n## T5. Controls: FA on z3-equivalent rewrites and renames, paired base FA and flip rate\n")
    L.append("# source: results/controls_fa.csv\n")
    L.append(md([dict(r, FA=ci(r, "FA_gt05", "FA_lo", "FA_hi"), diff=ci(r, "FA_minus_base", "diff_lo", "diff_hi"),
                      flip=ci(r, "flip_rate", "flip_lo", "flip_hi")) for r in cf if r["base_source"] != "ALL"],
                ["variant", "control_type", "base_source", "n", "n_insufficient", "FA", "FA_eq1", "paired_base_FA", "diff", "flip"]))
    inv = rcsv(E8 / "results" / "invariance_table.csv")
    ref = [r for r in inv if r["metric"] in ("c_align", "c_hyb", "c_nf") and r["family"] in ("RENAME_SYN", "RENAME_NONCE")
           and r["subset"] in ("E_bases", "all") and r["source"] in ("PERTURB_CONTROL", "PERTURB_E_bases")]
    seen, refs = set(), []
    for r in ref:
        k = (r["metric"], r["family"], r["threshold"])
        if k not in seen:
            seen.add(k)
            refs.append(r)
    L.append("\nReference rows copied from exp 8 (different thresholds; cited, not recomputed):\n")
    L.append(f"# source: {E8 / 'results' / 'invariance_table.csv'}\n")
    L.append(md(refs, ["metric", "family", "threshold", "n_rows", "FA_on_correct", "base_FA", "flip_rate"]))
    # T6 typing
    ty = rcsv(RES / "typing_csc.csv")
    ts = json.loads((RES / "typing_summary.json").read_text())
    L.append("\n## T6. Same-vocabulary typed repair: error-type identification\n")
    L.append("# source: results/typing_csc.csv, results/typing_summary.json (exp-8 baselines cited from "
             f"{ts['source']})\n")
    L.append(f"Exp-8 baselines on E-base mutants: majority class {ts['majority_class']} {ts['majority_acc_exp8']:.3f}, chance "
             f"{ts['marginal_chance_exp8']:.3f}, ALIGN-medoid typing {ts['medoid_align_exp8']['acc']:.3f}, flash-lite judge "
             f"{ts['judge_flashlite_exp8']['acc']:.3f}, local Qwen3-8B judge {ts['judge_local_qwen8b_exp8']['acc']:.3f}, exp-8 oracle "
             f"{ts['oracle_strict_exp8']:.3f}. Recomputed here: majority {ts['majority_acc_recomputed']}, chance {ts['chance_recomputed']}.\n")
    L.append(md([dict(r, strict_ci=ci(r, "strict", "lo", "hi")) for r in ty if r["true_op"] in ("ALL", "ALL_excl_MEANING_RENAME")],
                ["target", "base_source", "true_op", "n", "strict_ci", "lenient", "repair_found", "no_target",
                 "oracle_strict_same_rows", "majority_class_acc_same_rows"]))
    L.append("\nPer operator:\n")
    L.append(md([dict(r, strict_ci=ci(r, "strict", "lo", "hi")) for r in ty if r["true_op"] not in ("ALL", "ALL_excl_MEANING_RENAME")
                 and r["base_source"] != "ALL"], ["target", "base_source", "true_op", "n", "strict_ci", "lenient", "repair_found"]))
    # T7 SIG
    sg = json.loads((RES / "rcomp_sig_csc.json").read_text())
    L.append("\n## T7. R_COMP SIG labelled check (development; controlled-vocabulary regime): k = 3 family-matched ablation\n")
    L.append("# source: results/rcomp_sig_csc.json\n")
    L.append(f"Pool: {sg['pool']}. {sg['note']}\n")
    L.append(md([{"metric": k, "n": v["n"], "AUROC_within_template": f"{v['est']:.3f} [{v['ci'][0]:.3f}, {v['ci'][1]:.3f}]"}
                 for k, v in sg["auroc_within_template"].items()], ["metric", "n", "AUROC_within_template"]))
    L.append("\nPaired deltas (same rows):\n")
    L.append(md([{"comparison": k, "n": v["n"], "a": v["auroc_a"], "b": v["auroc_b"],
                  "delta": f"{v['est']:.3f} [{v['ci'][0]:.3f}, {v['ci'][1]:.3f}]", "p(delta<=0)": v["p_one_sided_le0"]}
                 for k, v in sg["paired_delta"].items()], ["comparison", "n", "a", "b", "delta", "p(delta<=0)"]))
    L.append("\ne (ERROR endorsed) and d (CORRECT flagged) at c > 0.5, d split by matched reading:\n")
    L.append(md([{"metric": k, **v} for k, v in sg["e_d_at_0.5"].items()],
                ["metric", "n", "e_error_endorsed", "d_correct_flagged", "d_weak", "n_correct_weak", "d_strong", "n_correct_strong"]))
    # T8 FREE
    fr = json.loads((RES / "rcomp_free_labelfree.json").read_text())
    L.append("\n## T8. R_COMP FREE, label-free only (firewalled)\n")
    L.append("# source: results/rcomp_free_labelfree.json, results/firewall.json\n")
    L.append(f"CSC FREE cache: {fr['csc_free_cache']}.\n\nPairwise equivalence among FREE few-shot candidates of a sentence: "
             f"ALIGN {fr['free_align_class_id']['pairwise_equiv_rate']} (n pairs {fr['free_align_class_id']['n_pairs']}), "
             f"HYB {fr['free_hyb_class_id']['pairwise_equiv_rate']}. Cued (SIG) peer-peer exact agreement among deepseek / "
             f"phi-4 / gpt-4.1-mini: {fr['sigproxy_peer_peer_exact_agreement_on_SIG']['mean']} over "
             f"{fr['sigproxy_peer_peer_exact_agreement_on_SIG']['n_sentences']} sentences (label-free d proxy "
             f"{fr['sigproxy_peer_peer_exact_agreement_on_SIG']['label_free_d_proxy']}).\n")
    L.append(md([{"template": t, "ALIGN": fr["free_align_class_id"]["by_template"].get(t), "HYB": fr["free_hyb_class_id"]["by_template"].get(t)}
                 for t in fr["free_align_class_id"]["by_template"]], ["template", "ALIGN", "HYB"]))
    # T9 LOCAL2
    lo = json.loads((RES / "local2_anchoring.json").read_text())
    L.append("\n## T9. LOCAL2 (secondary, NOT the pre-registered peers): anchoring mechanism with small local peers\n")
    L.append("# source: results/local2_anchoring.json\n")
    if lo.get("status") == "OK":
        L.append(f"Peers: {lo['peers']}; {lo['n_bases']} E bases (of 40 drawn; the rest were not completed before the "
                 f"CPU deadline); rows scored {lo['n_rows_scored']} with status counts {lo['row_status_counts']} "
                 f"(k = 2; 'csc_insufficient_peers' = fewer than 2 parseable peers). Base endorsement rate "
                 f"{lo['base_endorsement_rate']} (prereg rule, insufficient = 0.5 counts as not flagged), "
                 f"{lo['base_endorsement_rate_excl_insufficient']} over the {lo['n_bases_sufficient']} bases with 2 parseable peers. "
                 f"Delta-anchor uses {lo['delta_anchor_rows_used']} new-signature rows where both peer sets are usable "
                 f"({lo['delta_anchor_rows_excluded_insufficient']} excluded). {lo['caveat']}.\n")
        L.append("Listed-symbol usage by role (mean over row x peer x symbol):\n")
        L.append(md([{"role": k, **v} for k, v in lo["symbol_usage_by_role"].items()], ["role", "rate", "n"]))
        L.append("\nWithin-sentence contrast (new-signature rows): e with own-signature peers vs e with base-signature peers:\n")
        L.append(md(lo["delta_anchor"], ["op_label", "n", "e_own_sig", "e_base_sig", "delta_anchor_rowlevel", "lo", "hi",
                                         "delta_anchor_peershare", "lo_share", "hi_share"]))
        L.append("\nPlacebo (operator labels shuffled within base):\n")
        L.append(md(lo["placebo_within_base_label_shuffle"], ["op_label_permuted", "n", "delta_anchor_rowlevel"]))
        L.append("\nP(peer formula equivalent to the mutant | the peer used the foreign / donor symbol): " +
                 json.dumps(lo["p_peer_eq_mutant_given_used_new_symbol"]) + "\n")
    else:
        L.append("LOCAL2 not run.\n")
    # T10 cost
    co = rcsv(RES / "cost_table.csv")
    L.append("\n## T10. Cost (units explicit)\n")
    L.append("# source: results/cost_table.csv, results/csc_job_manifest.json\n")
    L.append(md(co, ["item", "value", "unit", "source"]))
    man = json.loads((RES / "csc_job_manifest.json").read_text())
    L.append(f"\nProjected cost of the full pre-registered CSC run (all stages): ${man['projected_total_usd']} "
             f"(x1.1 = ${man['projected_total_usd_x1.1']}); per stage: {json.dumps(man['stages'])}.\n")
    # T11 gates
    g = json.loads((RES / "csc_gate_P.json").read_text())
    L.append("\n## T11. Gates\n")
    L.append("# source: results/csc_gate_P.json\n")
    L.append(md([{"gate": k, "verdict": (v.get("verdict") if isinstance(v, dict) else v)} for k, v in g.items()
                 if k in ("G3_P", "G4", "MT", "G5")], ["gate", "verdict"]))
    san = json.loads((RES / "sanity_checks.json").read_text())
    L.append("\n## T12. Sanity checks\n")
    L.append("# source: results/sanity_checks.json\n")
    L.append("```\n" + json.dumps(san, indent=1) + "\n```\n")
    (RES / "tables.md").write_text("\n".join(L))
    devs = {"D-BUDGET": dv,
            "D-PILOT": "pilot (30 signatures x 4 models) returned 403 on every call; prompt variant v1 kept (the v1b rule "
                       "needs pilot usage data); no projection from own pilot - sibling exp-9 per-call prices used instead",
            "D-RETEST": "test-retest subsample not run (no API)",
            "D-FREE-CACHE": "the label-free FREE CSC peer cache for iteration 5 was not generated; job manifest delivered",
            "D-LOCAL2": "a labelled secondary local-peer arm (qwen2.5-1.5b, gemma-2-2b; llama-3.2-1b dropped after 0/3 parseable "
                        "in a smoke test) was added on 40 E bases to measure the anchoring mechanism; never used for a gate",
            "D-SIGPROXY": "signature-cued outputs of the same families from exp 7 (closed glossed template vocabulary) used as a "
                          "k=3 proxy on R_COMP bases and SIG rows; never used for a gate",
            "D-TYPING-ADD_ANY": "ADD_ANY also conjoins NEGATED target literals (a dropped '¬P(x)' is otherwise unreachable at depth 1)",
            "D-TYPING-SHORTCUT": "sound MISSING_PREDS > 2 shortcut (VOCAB_GAP) skips searches that cannot succeed at depth 2",
            "D-TEXT": "27 exp-7 SIG/FREE sentence ids absent from dataset 3's final export: text taken from exp 7's own "
                      "rcomp/work/rcomp_sentences.json (plan fallback)",
            "D-FREE-ROWS": "exp 7 has 2,652 FREE rows (10 few-shot slots + 2 zero-shot) of which 2,265 parse; the planned "
                           "'2,024' referred to the SIG primary pool"}
    (RES / "deviations.json").write_text(json.dumps(devs, indent=1, ensure_ascii=False))


if __name__ == "__main__":
    main()
